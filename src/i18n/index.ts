const DICTS: Record<Lang, Dict> = { en, zh, es, ko, ja, ru, pt, vi, tr };

export function t(
  lang: Lang | string | null | undefined,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const l = normalizeLang(lang ?? undefined);
  let s = DICTS[l][key] ?? DICTS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}
